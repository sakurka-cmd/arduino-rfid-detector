// Image embed
// ═══════════════════════════════════════════
function embedImage(path, w, h) {
  const buf = fs.readFileSync(path);
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 200, after: 200 },
    children: [
      new ImageRun({ data: buf, transformation: { width: w, height: h }, type: "png" }),
    ],
  });
}

