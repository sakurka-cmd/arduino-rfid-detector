// ═══════════════════════════════════════════
// Table builder
// ═══════════════════════════════════════════
function buildTable(headers, rows) {
  const hdrCells = headers.map((h) =>
    new TableCell({
      shading: { type: ShadingType.CLEAR, fill: c(P.headerBg) },
      borders: {
        top: { style: BorderStyle.SINGLE, size: 2, color: c(P.headerBg) },
        bottom: { style: BorderStyle.SINGLE, size: 2, color: c(P.headerBg) },
        left: NB, right: NB,
      },
      margins: { top: 60, bottom: 60, left: 120, right: 120 },
      children: [new Paragraph({ children: [new TextRun({ text: h, bold: true, size: 21, color: c(P.headerText) })] })],
    })
  );

  const dataRows = rows.map((row, idx) =>
    new TableRow({
      children: row.map((cell) =>
        new TableCell({
          shading: { type: ShadingType.CLEAR, fill: idx % 2 === 0 ? c(P.tblSurface) : "FFFFFF" },
          borders: {
            top: NB, bottom: { style: BorderStyle.SINGLE, size: 1, color: c(P.innerLine) },
            left: NB, right: NB,
          },
          margins: { top: 50, bottom: 50, left: 120, right: 120 },
          children: [new Paragraph({ children: [new TextRun({ text: cell, size: 21, color: c("1A2B40") })] })],
        })
      ),
    })
  );

  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 2, color: c(P.headerBg) },
      bottom: { style: BorderStyle.SINGLE, size: 2, color: c(P.headerBg) },
      left: NB, right: NB,
      insideHorizontal: NB, insideVertical: NB,
    },
    rows: [new TableRow({ children: hdrCells }), ...dataRows],
  });
}

